const DEMAND_SCORE = { S: 4, A: 3, B: 2, C: 1 };
const COMP_SCORE = { L: 3, M: 2, H: 1 };
const DIFF_SCORE = { E: 3, N: 2, D: 1 };
const DEMAND_KR = { S: "매우높음", A: "높음", B: "중간", C: "낮음" };
const COMP_KR = { H: "높음", M: "보통", L: "낮음" };
const DIFF_KR = { E: "쉬움", N: "보통", D: "어려움" };

const rows = [];
const seen = new Set();
CATS.forEach((c) => {
  c.items.forEach((it) => {
    var kw, demand, comp, diff;
    if (Array.isArray(it)) { kw = it[0]; demand = it[1] || c.def.demand; comp = it[2] || c.def.comp; diff = it[3] || c.def.diff; }
    else { kw = it; demand = c.def.demand; comp = c.def.comp; diff = c.def.diff; }
    if (seen.has(kw)) return;
    seen.add(kw);
    // 가성비 점수: 수요 높고 + 경쟁 낮고 + 제작 쉽고 + 수익 좋을수록 높음
    var moneyBonus = /대출|부동산|금융|보험|카드/.test(c.money) ? 2 : (/제휴/.test(c.money) ? 1 : 0);
    var score = DEMAND_SCORE[demand] * 2 + COMP_SCORE[comp] * 2 + DIFF_SCORE[diff] + moneyBonus;
    rows.push({ category: c.name, kw, demand, comp, diff, money: c.money, score });
  });
});

rows.sort((a, b) => b.score - a.score || a.category.localeCompare(b.category));

