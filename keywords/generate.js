rows.forEach((r, i) => {
  csv += [i + 1, r.kw, r.category, DEMAND_KR[r.demand], COMP_KR[r.comp], DIFF_KR[r.diff], r.money, r.score].join(",") + "\n";
});
fs.writeFileSync(path.join(__dirname, "keywords.csv"), csv, "utf8");

